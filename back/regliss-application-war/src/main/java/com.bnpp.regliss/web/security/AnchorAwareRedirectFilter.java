package com.bnpp.regliss.web.security;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.web.util.UriUtils;

import javax.servlet.*;
import javax.servlet.http.HttpServletResponse;
import javax.servlet.http.HttpServletResponseWrapper;
import java.io.IOException;
import java.io.PrintWriter;
import java.net.URI;
import java.net.URISyntaxException;
import java.nio.charset.StandardCharsets;

public class AnchorAwareRedirectFilter implements Filter {

    private static final Logger log = LoggerFactory.getLogger(AnchorAwareRedirectFilter.class);

    @Override
    public void init(FilterConfig filterConfig) throws ServletException {
        //intentionally left empty
    }

    @Override
    public void doFilter(ServletRequest request, ServletResponse response, FilterChain chain)
            throws IOException, ServletException {
        SmartRedirectResponseWrapper responseWrapper = new SmartRedirectResponseWrapper((HttpServletResponse) response);
        try {
            chain.doFilter(request, responseWrapper);
        } finally {
            if (responseWrapper.getRedirectLocation() != null) {
                writeRedirectPage((HttpServletResponse) response, UriUtils.encode(UriUtils.decode(responseWrapper.getRedirectLocation(), StandardCharsets.UTF_8.toString()),
                        StandardCharsets.UTF_8.toString()));
            }
        }
    }

    private void writeRedirectPage(HttpServletResponse response, String redirectLocation) throws IOException {
        String sanitizedURI=sanitize (redirectLocation);

        response.setStatus(403);
        response.setContentType("text/html");
        /** the redirect location is not directly obtained from user request, instead it is a redirect generated by this application container
         * and always points to a resource located in this application context
         * there is only one place where we redirect a request , see RedirectToIndexHtml class, but only request parameters (what follows ? in requested URL)
         * are used to pass as parameters to the new location.Before that request parameters are sanitized and phishing is not possible
         * as the new URL points to a resource from this app context
         */
        response.addHeader("Location", sanitizedURI);//NOSONAR see comment above

        writeRedirectHtml(response.getWriter(), sanitizedURI);
    }
    private static String sanitize(String redirectLocation) {
        URI uri ;
        try {
            uri = new URI(redirectLocation.replace("\n", "").replace("\r", "").replace("'", "").replace("<", "")
                    .replace(">", ""));
            return uri.toASCIIString();
        } catch (URISyntaxException e) {
            return "";
        }
    }

    private void writeRedirectHtml(PrintWriter writer, String redirectLocation) {
        writer.printf("<html><head><title>Redirecting to %s</title></head>", redirectLocation);
        writer.print("<body style='text-align:center;'>");
        writer.printf("<p>Your browser is automatically redirected... </p><p id='ifNot' style='display:none'>If not, please click <a href='%s'>here</a></p>", redirectLocation);
        writer.print("<script>");
        if (log.isDebugEnabled()) {
            writer.printf("console.log('Redirecting to %s');", redirectLocation);
        }
        writer.print("if (window.location.hash) localStorage['anchorBeforeRedirect'] = window.location.hash;");
        writer.printf("window.location = '%s';", redirectLocation);
        writer.print("setTimeout(function() {document.getElementById('ifNot').style.display='block';}, 10000);");
        writer.print("</script>");
        writer.print("</body></html>");
    }

    @Override
    public void destroy() {
        //intentionally left empty
    }

    public class SmartRedirectResponseWrapper extends HttpServletResponseWrapper {
        private String redirectLocation;

        public String getRedirectLocation() {
            return redirectLocation;
        }
        public SmartRedirectResponseWrapper(HttpServletResponse response) {
            super(response);
        }
        // Spring security ends up calling THIS function whenever it wants to redirect the browser.
        @Override
        public void sendRedirect(String location) throws IOException {
            redirectLocation = location; // stop sending 302 for AJAX requests
            //Instead, intercept the redirect location and send a 403 + Location header.
        }
    }
}

